-- =============================================================================
-- CineConecta · PostgreSQL · 04_index_experiment.sql
-- Experimento controlado de índices (antes vs después) sobre ~100.000 suscripciones
-- y pagos en un esquema temporal/aislado de experimento para no alterar los datos
-- funcionales ni los índices permanentes de cineconecta.
--
-- Mide dos consultas críticas de billing/reporting:
--   Q1: Suscripción vigente e historial de una cuenta (ix_subscriptions_account_starts)
--   Q2: Informe de ingresos por plan en un rango de fechas (ix_payments_paidat + ix_subscriptions_plan)
-- =============================================================================

DROP SCHEMA IF EXISTS exp_billing CASCADE;
CREATE SCHEMA exp_billing;

CREATE TABLE exp_billing.plans AS TABLE cineconecta.plans;
ALTER TABLE exp_billing.plans ADD PRIMARY KEY (planid);

CREATE TABLE exp_billing.subscriptions (
    subscriptionid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accountid      INTEGER NOT NULL,
    planid         INTEGER NOT NULL,
    startsat       TIMESTAMPTZ NOT NULL,
    endsat         TIMESTAMPTZ NOT NULL
);

CREATE TABLE exp_billing.payments (
    paymentid      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriptionid INTEGER NOT NULL,
    paidat         TIMESTAMPTZ NOT NULL,
    amount         NUMERIC(12,2) NOT NULL,
    reference      VARCHAR(40) NOT NULL
);

-- Carga de volumen: 100.000 suscripciones históricas distribuidas en 20.000 cuentas
-- (5 períodos no superpuestos por cuenta, escalonados por día) + 100.000 pagos.
INSERT INTO exp_billing.subscriptions (subscriptionid, accountid, planid, startsat, endsat)
SELECT
    ((a - 1) * 5 + p) AS subscriptionid,
    a AS accountid,
    ((a + p) % 3) + 1 AS planid,
    TIMESTAMPTZ '2025-01-01 00:00:00+00' + ((a % 180) * INTERVAL '1 day') + ((p - 1) * INTERVAL '35 days') AS startsat,
    TIMESTAMPTZ '2025-01-01 00:00:00+00' + ((a % 180) * INTERVAL '1 day') + ((p - 1) * INTERVAL '35 days') + INTERVAL '720 hours' AS endsat
FROM generate_series(1, 20000) AS a,
     generate_series(1, 5)     AS p;

INSERT INTO exp_billing.payments (subscriptionid, paidat, amount, reference)
SELECT
    s.subscriptionid,
    s.startsat,
    CASE s.planid WHEN 1 THEN 16900.00 WHEN 2 THEN 26900.00 ELSE 38900.00 END,
    'EXP-' || s.subscriptionid
FROM exp_billing.subscriptions s;

ANALYZE exp_billing.plans;
ANALYZE exp_billing.subscriptions;
ANALYZE exp_billing.payments;

\echo '=== TAMAÑO BASE SIN ÍNDICES SECUNDARIOS ==='
SELECT relname,
       pg_size_pretty(pg_relation_size(c.oid))       AS table_size,
       pg_size_pretty(pg_indexes_size(c.oid))        AS indexes_size,
       pg_size_pretty(pg_total_relation_size(c.oid)) AS total_size
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'exp_billing' AND c.relkind = 'r'
ORDER BY relname;

\echo '=== Q1 ANTES (SIN ix_subscriptions_account_starts): historial y vigente por cuenta ==='
EXPLAIN (ANALYZE, BUFFERS)
SELECT s.subscriptionid, s.planid, s.startsat, s.endsat
FROM exp_billing.subscriptions s
WHERE s.accountid = 15432
ORDER BY s.startsat DESC;

\echo '=== Q2 ANTES (SIN ix_payments_paidat / ix_subscriptions_plan): ingresos por plan en 7 días ==='
EXPLAIN (ANALYZE, BUFFERS)
SELECT pl.planid, pl.name, COUNT(pay.paymentid), COALESCE(SUM(pay.amount), 0)
FROM exp_billing.plans pl
JOIN exp_billing.subscriptions sub ON sub.planid = pl.planid
JOIN exp_billing.payments pay ON pay.subscriptionid = sub.subscriptionid
WHERE pay.paidat >= TIMESTAMPTZ '2025-03-10 00:00:00+00'
  AND pay.paidat <  TIMESTAMPTZ '2025-03-17 00:00:00+00'
GROUP BY pl.planid, pl.name
ORDER BY pl.planid;

-- Crear los índices del esquema productivo (01_schema.sql)
CREATE INDEX ix_exp_sub_account_starts ON exp_billing.subscriptions (accountid, startsat DESC);
CREATE INDEX ix_exp_sub_plan           ON exp_billing.subscriptions (planid);
CREATE INDEX ix_exp_pay_paidat         ON exp_billing.payments (paidat);
CREATE INDEX ix_exp_pay_sub            ON exp_billing.payments (subscriptionid);

ANALYZE exp_billing.subscriptions;
ANALYZE exp_billing.payments;

\echo '=== TAMAÑO CON ÍNDICES SECUNDARIOS ==='
SELECT relname,
       pg_size_pretty(pg_relation_size(c.oid))       AS table_size,
       pg_size_pretty(pg_indexes_size(c.oid))        AS indexes_size,
       pg_size_pretty(pg_total_relation_size(c.oid)) AS total_size
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'exp_billing' AND c.relkind = 'r'
ORDER BY relname;

\echo '=== Q1 DESPUÉS (CON ix_subscriptions_account_starts) ==='
EXPLAIN (ANALYZE, BUFFERS)
SELECT s.subscriptionid, s.planid, s.startsat, s.endsat
FROM exp_billing.subscriptions s
WHERE s.accountid = 15432
ORDER BY s.startsat DESC;

\echo '=== Q2 DESPUÉS (CON ix_payments_paidat y ix_subscriptions_plan) ==='
EXPLAIN (ANALYZE, BUFFERS)
SELECT pl.planid, pl.name, COUNT(pay.paymentid), COALESCE(SUM(pay.amount), 0)
FROM exp_billing.plans pl
JOIN exp_billing.subscriptions sub ON sub.planid = pl.planid
JOIN exp_billing.payments pay ON pay.subscriptionid = sub.subscriptionid
WHERE pay.paidat >= TIMESTAMPTZ '2025-03-10 00:00:00+00'
  AND pay.paidat <  TIMESTAMPTZ '2025-03-17 00:00:00+00'
GROUP BY pl.planid, pl.name
ORDER BY pl.planid;

DROP SCHEMA exp_billing CASCADE;
