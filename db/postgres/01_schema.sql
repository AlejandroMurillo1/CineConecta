-- =============================================================================
-- CineConecta · PostgreSQL · 01_schema.sql
-- Modelo relacional suministrado + restricciones, índices, vista y trigger
-- para las reglas del negocio.
--
-- Convenciones:
--   * Identificadores SIN comillas: PostgreSQL los guarda en minúsculas
--     (accountId -> accountid). Hibernate, con PhysicalNamingStrategyStandardImpl,
--     tampoco usa comillas, así que coinciden.
--   * Cambios respecto al modelo suministrado (justificados en el README):
--       - VARCHAR2 -> VARCHAR, NUMBER -> NUMERIC (traducción de Oracle a PostgreSQL).
--       - TIMESTAMP -> TIMESTAMPTZ (instantes absolutos, comparables con las
--         fechas UTC de MongoDB en el informe de consumo).
--       - PLANS.isActive (nuevo): gestión de planes por el administrador.
-- =============================================================================

SET ROLE cine_owner;
SET search_path = cineconecta, public;

-- -----------------------------------------------------------------------------
-- ACCOUNTS
-- -----------------------------------------------------------------------------
CREATE TABLE accounts (
    accountId     INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    fullName      VARCHAR(150) NOT NULL,
    email         VARCHAR(254) NOT NULL,
    passwordHash  VARCHAR(255) NOT NULL,
    createdAt     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_accounts PRIMARY KEY (accountId),
    CONSTRAINT ck_accounts_email CHECK (position('@' IN email) > 1)
);
-- Correo único sin distinguir mayúsculas (índice del modelo suministrado).
CREATE UNIQUE INDEX ux_accounts_email_ci ON accounts (LOWER(email));

-- -----------------------------------------------------------------------------
-- PLANS
-- -----------------------------------------------------------------------------
CREATE TABLE plans (
    planId       INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR(60)   NOT NULL,
    price        NUMERIC(12,2) NOT NULL,
    maxProfiles  INTEGER       NOT NULL,
    isActive     CHAR(1)       NOT NULL DEFAULT 'Y',
    CONSTRAINT pk_plans PRIMARY KEY (planId),
    CONSTRAINT uq_plans_name UNIQUE (name),
    CONSTRAINT ck_plans_price CHECK (price > 0),
    CONSTRAINT ck_plans_maxprofiles CHECK (maxProfiles BETWEEN 1 AND 10),
    CONSTRAINT ck_plans_isactive CHECK (isActive IN ('Y', 'N'))
);

-- -----------------------------------------------------------------------------
-- PROFILES
-- -----------------------------------------------------------------------------
CREATE TABLE profiles (
    profileId     INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    accountId     INTEGER     NOT NULL,
    name          VARCHAR(60) NOT NULL,
    maxAgeRating  INTEGER     NOT NULL,
    isActive      CHAR(1)     NOT NULL DEFAULT 'Y',
    CONSTRAINT pk_profiles PRIMARY KEY (profileId),
    CONSTRAINT fk_profiles_account FOREIGN KEY (accountId) REFERENCES accounts (accountId),
    CONSTRAINT ck_profiles_agerating CHECK (maxAgeRating BETWEEN 0 AND 18),
    CONSTRAINT ck_profiles_isactive CHECK (isActive IN ('Y', 'N'))
);
-- Nombre único dentro de la cuenta (índice del modelo suministrado).
-- Su primera columna (accountId) también sirve de índice para la FK.
CREATE UNIQUE INDEX ux_profiles_name_ci ON profiles (accountId, LOWER(name));

-- -----------------------------------------------------------------------------
-- SUBSCRIPTIONS
-- -----------------------------------------------------------------------------
CREATE TABLE subscriptions (
    subscriptionId  INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    accountId       INTEGER     NOT NULL,
    planId          INTEGER     NOT NULL,
    startsAt        TIMESTAMPTZ NOT NULL,
    endsAt          TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_subscriptions PRIMARY KEY (subscriptionId),
    CONSTRAINT fk_subscriptions_account FOREIGN KEY (accountId) REFERENCES accounts (accountId),
    CONSTRAINT fk_subscriptions_plan FOREIGN KEY (planId) REFERENCES plans (planId),
    -- Todas las suscripciones duran exactamente 30 días (720 horas).
    CONSTRAINT ck_subscriptions_30_days CHECK (endsAt = startsAt + INTERVAL '720 hours'),
    -- Sin períodos superpuestos para una misma cuenta. El rango '[)' replica la
    -- vigencia del enunciado: incluye el inicio y excluye el fin.
    -- Si dos compras simultáneas se cruzan, la segunda falla con SQLSTATE 23P01.
    CONSTRAINT ex_subscriptions_no_overlap EXCLUDE USING gist (
        accountId WITH =,
        tstzrange(startsAt, endsAt, '[)') WITH &&
    )
);
-- Historial y suscripción vigente de una cuenta.
CREATE INDEX ix_subscriptions_account_starts ON subscriptions (accountId, startsAt DESC);
-- FK hacia PLANS e informe de ingresos por plan.
CREATE INDEX ix_subscriptions_plan ON subscriptions (planId);

-- -----------------------------------------------------------------------------
-- PAYMENTS
-- -----------------------------------------------------------------------------
CREATE TABLE payments (
    paymentId       INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    subscriptionId  INTEGER       NOT NULL,
    paidAt          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    amount          NUMERIC(12,2) NOT NULL,
    reference       VARCHAR(100)  NOT NULL,
    CONSTRAINT pk_payments PRIMARY KEY (paymentId),
    CONSTRAINT fk_payments_subscription FOREIGN KEY (subscriptionId) REFERENCES subscriptions (subscriptionId),
    -- Restricciones únicas del modelo suministrado.
    CONSTRAINT uq_payments_subscription UNIQUE (subscriptionId),
    CONSTRAINT uq_payments_reference UNIQUE (reference),
    CONSTRAINT ck_payments_amount CHECK (amount > 0)
);
-- Informe de ingresos por plan (filtro por fecha de pago).
CREATE INDEX ix_payments_paidat ON payments (paidAt);

-- -----------------------------------------------------------------------------
-- Cada suscripción confirmada debe tener EXACTAMENTE un pago.
-- uq_payments_subscription garantiza "como máximo uno"; este trigger diferido
-- garantiza "al menos uno": se revisa al hacer COMMIT, así que una suscripción
-- sin pago hace fallar toda la transacción y no queda ningún registro parcial.
-- -----------------------------------------------------------------------------
CREATE FUNCTION fn_subscription_requires_payment()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = cineconecta, public
AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM payments p WHERE p.subscriptionId = NEW.subscriptionId) THEN
        RAISE EXCEPTION 'La suscripción % no tiene un pago registrado', NEW.subscriptionId
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_subscription_requires_payment
    AFTER INSERT ON subscriptions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION fn_subscription_requires_payment();

-- -----------------------------------------------------------------------------
-- Vista: suscripción vigente de cada cuenta en este momento (como mucho una, por
-- la EXCLUDE). Es auxiliar: sirve para consultas manuales, informes con
-- cine_report y la demostración en la sustentación.
-- La aplicación NO la consulta: aplica la misma condición [inicio, fin) desde JPA
-- (SubscriptionRepository.findActiveAt) porque necesita evaluar la vigencia en un
-- instante dado (p. ej. "plan vigente al iniciar cada sesión") y con un solo reloj,
-- el Clock de la aplicación, en lugar de now() de la base.
-- -----------------------------------------------------------------------------
CREATE VIEW v_current_subscription AS
SELECT s.subscriptionId,
       s.accountId,
       s.planId,
       p.name        AS planName,
       p.maxProfiles,
       s.startsAt,
       s.endsAt
FROM subscriptions s
JOIN plans p ON p.planId = s.planId
WHERE s.startsAt <= now()
  AND now() < s.endsAt;

-- -----------------------------------------------------------------------------
-- Comentarios (sirven de base para el catálogo de objetos del entregable).
-- -----------------------------------------------------------------------------
COMMENT ON TABLE accounts      IS 'Cuentas de los titulares. Fuente de verdad de clientes.';
COMMENT ON TABLE profiles      IS 'Perfiles de visualización. Se desactivan, no se borran.';
COMMENT ON TABLE plans         IS 'Planes de suscripción. Precio y máximo de perfiles no cambian tras crearse.';
COMMENT ON TABLE subscriptions IS 'Historial de suscripciones de 30 días. Sin períodos superpuestos por cuenta.';
COMMENT ON TABLE payments      IS 'Pago simulado (aprobado) que respalda exactamente una suscripción.';
COMMENT ON COLUMN plans.isActive IS 'Cambio estructural: un plan inactivo no se ofrece en nuevas contrataciones.';
COMMENT ON COLUMN payments.amount IS 'Copia del precio del plan al momento del pago (dato histórico).';
COMMENT ON VIEW v_current_subscription IS 'Suscripción vigente: startsAt <= now() < endsAt.';

RESET ROLE;
